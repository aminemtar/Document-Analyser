List<dynamic> _list(dynamic v) => v is List ? v : const [];

/// Plain-text version of an analysis, for copying, sharing or printing.
String analysisToText(String name, Map<String, dynamic> data) {
  final out = StringBuffer('$name\n\n${data['summary'] ?? ''}\n');
  void section(String title, dynamic values, String Function(dynamic) line) {
    final items = _list(values);
    if (items.isEmpty) return;
    out.writeln('\n$title');
    for (final item in items) {
      out.writeln('- ${line(item)}');
    }
  }

  String pair(dynamic a, dynamic b) => [a, b]
      .where((v) => v != null && v.toString().trim().isNotEmpty)
      .join(': ');

  section('Key details', data['key_details'], (i) => i.toString());
  section('Risks', data['risks'],
      (i) => i is Map ? pair(i['title'], i['detail']) : i.toString());
  section(
      'Important dates',
      data['important_dates'],
      (i) => i is Map
          ? [pair(i['label'], i['date']), i['note']]
              .where((v) => v != null && v.toString().trim().isNotEmpty)
              .join(' - ')
          : i.toString());
  section('Amounts', data['amounts'],
      (i) => i is Map ? pair(i['label'], i['value']) : i.toString());
  section('Action items', data['action_items'], (i) => i.toString());
  out.writeln('\nGenerated by DocuMind AI. Check important details in the original document.');
  return out.toString();
}

const _backupFormat = 'documind-backup';
const _backupVersion = 1;

/// A backup of the library list and every analysis. It does not contain the
/// original files, which stay on this device.
String buildBackup(List<DocItem> docs, {DateTime? now}) => jsonEncode({
      'format': _backupFormat,
      'version': _backupVersion,
      'createdAt': (now ?? DateTime.now()).toUtc().toIso8601String(),
      'documents': [
        for (final d in docs)
          // Device paths mean nothing on another phone.
          {...d.toJson(), 'path': null},
      ],
    });

/// Reads a backup. Throws a FormatException with a readable message when the
/// file is not a DocuMind backup or comes from a newer app version.
List<DocItem> parseBackup(String source) {
  final Object? decoded;
  try {
    decoded = jsonDecode(source);
  } catch (_) {
    throw const FormatException('This file is not a DocuMind backup.');
  }
  if (decoded is! Map || decoded['format'] != _backupFormat) {
    throw const FormatException('This file is not a DocuMind backup.');
  }
  final version = decoded['version'];
  if (version is! int || version > _backupVersion) {
    throw const FormatException(
        'This backup was made by a newer version of DocuMind. Update the app and try again.');
  }
  return [
    for (final item in _list(decoded['documents']))
      if (item is Map) DocItem.fromJson(Map<String, dynamic>.from(item)),
  ];
}

/// Adds restored documents to [current], skipping any that are already there
/// (same name, date and analysis).
List<DocItem> mergeRestored(List<DocItem> current, List<DocItem> restored) {
  bool same(DocItem a, DocItem b) =>
      a.name == b.name && a.date == b.date && a.analysisJson == b.analysisJson;
  return [
    for (final r in restored)
      if (!current.any((c) => same(c, r))) r,
  ];
}

abstract final class ExportService {
  static Future<void> shareAnalysis(String name, Map<String, dynamic> data) =>
      SharePlus.instance.share(ShareParams(
          text: analysisToText(name, data), subject: 'Analysis of $name'));

  static Future<void> shareBackup(List<DocItem> docs) async {
    final now = DateTime.now();
    String two(int v) => v.toString().padLeft(2, '0');
    final dir = await getTemporaryDirectory();
    final file = File(
        '${dir.path}/documind-backup-${now.year}${two(now.month)}${two(now.day)}.json');
    await file.writeAsString(buildBackup(docs, now: now), flush: true);
    await SharePlus.instance.share(ShareParams(
        files: [XFile(file.path, mimeType: 'application/json')],
        subject: 'DocuMind backup'));
  }
}
